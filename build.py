#!/usr/bin/env python3
"""Build Logseq bundles and a reproducible install ZIP using only Python's stdlib."""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent


# Read config maps structurally; never evaluate Clojure forms.
TOKEN = re.compile(r'\s+|;[^\n]*|,|#?"(?:\\.|[^"\\])*"|#\{|[{}\[\]()]|[^\s,{}\[\]()";]+')


def read_map(text):
    tokens = []
    position = 0
    for match in TOKEN.finditer(text):
        if match.start() != position:
            raise ValueError(f"Unsupported config syntax at {position}")
        position = match.end()
        token = match.group()
        if token.isspace() or token.startswith(";") or token == ",":
            continue
        tokens.append((token, match.start(), match.end()))
    if position != len(text):
        raise ValueError("Unterminated string in config")
    cursor = 0

    def form():
        nonlocal cursor
        if cursor == len(tokens):
            raise ValueError("Unexpected end of config")
        token, start, end = tokens[cursor]
        cursor += 1
        closing = {"{": "}", "[": "]", "(": ")", "#{": "}"}.get(token)
        if closing:
            values = []
            while cursor < len(tokens) and tokens[cursor][0] != closing:
                values.append(form())
            if cursor == len(tokens):
                raise ValueError("Unclosed config collection")
            end = tokens[cursor][2]
            cursor += 1
            if token == "{":
                if len(values) % 2:
                    raise ValueError("Map must have key/value pairs")
                result = {}
                for key, value in zip(values[::2], values[1::2]):
                    if not isinstance(key, str) or not (key.startswith(":") or key.startswith('"')):
                        raise ValueError("Config maps require keyword or string keys")
                    if key in result:
                        raise ValueError(f"Duplicate config key: {key}")
                    result[key] = value
                return result
            return text[start:end]
        if token in {"}", "]", ")"} or token.startswith(("#", "'", "`", "~", "^", "@", "\\")):
            if not token.startswith('#"'):
                raise ValueError(f"Unsupported config form: {token}")
        return text[start:end]

    value = form()
    if cursor != len(tokens) or not isinstance(value, dict):
        raise ValueError("Config must contain exactly one map")
    return value


def merge(base, overrides):
    result = dict(base)
    for key, value in overrides.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = merge(result[key], value)
        else:
            result[key] = value
    return result


def render(value, indent=0):
    if not isinstance(value, dict):
        return value
    if not value:
        return "{}"
    padding = " " * (indent + 2)
    return "{\n" + "\n".join(padding + key + " " + render(item, indent + 2)
                                 for key, item in value.items()) + "\n" + " " * indent + "}"


def compile_config(*layers):
    result = {}
    for layer in layers:
        result = merge(result, read_map(layer))
    return (";; Generated by build.py; edit config sources in src/manifest.json.\n" +
            render(result) + "\n").encode()


def bundles():
    manifest = json.loads((ROOT / "src/manifest.json").read_text())
    result = {}
    for output, sources in manifest.items():
        if output not in {"logseq/custom.js", "logseq/custom.css", "logseq/config.edn"}:
            raise ValueError(f"Unexpected output: {output}")
        if not sources or len(set(sources)) != len(sources):
            raise ValueError(f"Empty or repeated sources: {output}")
        chunks = []
        for source in sources:
            path = (ROOT / source).resolve()
            if not path.is_relative_to((ROOT / "src").resolve()):
                raise ValueError(f"Source outside src: {source}")
            chunks.append(path.read_bytes())
        if output == "logseq/config.edn":
            result[output] = compile_config(*(chunk.decode("utf-8") for chunk in chunks))
        else:
            result[output] = b"".join(chunks)
    if set(result) != {"logseq/custom.js", "logseq/custom.css", "logseq/config.edn"}:
        raise ValueError("JS, CSS and config outputs are required")
    return result


def archive(path, outputs):
    files = {**outputs, "README.md": (ROOT / "README.md").read_bytes(),
             "LICENSE": (ROOT / "LICENSE").read_bytes()}
    files["SHA256SUMS"] = "".join(
        f"{hashlib.sha256(data).hexdigest()}  {name}\n"
        for name, data in sorted(files.items())
    ).encode()
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as target:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            target.writestr(info, data)
    with zipfile.ZipFile(path) as target:
        if target.testzip() is not None:
            raise ValueError("Archive integrity check failed")


def run_tests():
    subprocess.run([sys.executable, str(ROOT / "test.py"), "--no-build"],
                   cwd=ROOT, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if dist bundles differ from sources")
    parser.add_argument("--build-only", action="store_true", help="Build files without tests or ZIP")
    parser.add_argument("--archive", type=Path, help="Override the ZIP output path (default: dist/logseq-config.zip)")
    args = parser.parse_args()
    if args.check and (args.build_only or args.archive):
        parser.error("--check cannot be combined with build or archive options")
    if args.build_only and args.archive:
        parser.error("--build-only cannot be combined with --archive")
    target = args.archive or ROOT / "dist/logseq-config.zip"
    if not args.check and not args.build_only:
        target.unlink(missing_ok=True)
    outputs = bundles()
    for name, data in outputs.items():
        path = ROOT / "dist" / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                parser.exit(1, f"Outdated bundle: {name}; run python3 build.py\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if args.check or args.build_only:
        return
    run_tests()
    archive(target, outputs)
    print(f"Build and tests passed. Archive: {target}")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        sys.exit(error.returncode)
    except (OSError, ValueError) as error:
        sys.exit(f"Build failed: {error}")
